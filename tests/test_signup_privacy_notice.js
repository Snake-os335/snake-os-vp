'use strict';
const fs = require('fs');
const assert = require('assert');
const html = fs.readFileSync(require('path').join(__dirname, '..', 'index.html'), 'utf8');
const phrase = 'La cuenta que crees se guarda en el servidor';
const start = html.indexOf('<div class="card hidden" id="signupView">');
assert.ok(start > 0, 'signupView');
const chunk = html.slice(start, start + 1800);
assert.ok(chunk.indexOf('id="dogaCuentaAviso"') < chunk.indexOf('<h1'), 'el aviso va antes del título');
assert.ok(chunk.indexOf('doga-cuenta-frase') < chunk.indexOf('<form'), 'la frase va antes del formulario');
assert.strictEqual(chunk.includes('<a '), false);
const strong = chunk.indexOf('<strong>' + phrase + '</strong>');
assert.ok(strong > 0, 'frase exacta en strong');
assert.ok(strong < chunk.indexOf('The account you create is stored on the server'));
assert.ok(html.includes('.doga-cuenta-frase{margin:0 0 8px;font-size:1.55rem;line-height:1.25;font-weight:800}'));
assert.ok(html.includes('.doga-cuenta-aviso{margin:0 0 12px;text-align:left;scroll-margin-top:12px}'));
assert.ok(html.includes("aviso.scrollIntoView({block:'start', inline:'nearest'})"));
assert.ok(html.includes('@media (max-width:360px){.doga-cuenta-frase{font-size:1.25rem}}'));
assert.ok(html.includes('#lock:has(#signupView:not(.hidden)){justify-content:flex-start !important;align-items:center}'));
assert.ok(html.includes('tabindex="0"'));
console.log('signup privacy notice ok');
